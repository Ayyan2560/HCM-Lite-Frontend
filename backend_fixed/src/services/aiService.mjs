const SYSTEM_PROMPT = `You are the HCM Lite AI assistant for a Human Capital Management platform.
Answer only with data returned by the provided read-only tools and company policy.
Rules:
- Never invent numbers. If a tool returns no data, say so plainly.
- You cannot modify data: never claim to approve leave, edit attendance, or change payroll.
- Respect role scope. Employees may only see their own records.
- Be concise (max 120 words), professional, and format money with the company currency.`;

function money(currency, value) {
  return `${currency} ${Number(value || 0).toLocaleString('en-US', { maximumFractionDigits: 0 })}`;
}

export function isProviderConfigured() {
  return Boolean(env.aiApiKey);
}

/**
 * Chat endpoint entry point. Uses an OpenAI-compatible chat-completions API when
 * AI_API_KEY is configured; otherwise (or on provider failure) returns a clearly
 * labelled deterministic answer built from the same read-only tool registry.
 */
export async function chat({ user, message, history = [] }) {
  const org = await getOrganization();
  const config = orgConfig(org);
  const { dateKey: todayKey } = nowParts(config.timezone);

  if (isProviderConfigured()) {
    try {
      const result = await callProvider({ user, message, history, config });
      if (result) {
        return {
          ...result,
          mode: 'live',
          label: 'AI-assisted answer',
          model: env.aiModel,
          providerConfigured: true
        };
      }
    } catch (error) {
      const fallback = await deterministicAnswer({ user, message, org, config, todayKey, history });
      return {
        ...fallback,
        mode: 'fallback',
        label: 'Offline assistant (AI provider unavailable)',
        providerConfigured: true,
        notice: `The hosted AI provider could not be reached (${error.message}). This answer was generated by the built-in rules engine.`
      };
    }
  }

  const fallback = await deterministicAnswer({ user, message, org, config, todayKey, history });
  return {
    ...fallback,
    mode: 'fallback',
    label: 'Offline assistant (no AI key configured)',
    providerConfigured: false,
    notice: 'No AI_API_KEY is configured, so this answer comes from HCM Lite’s deterministic rules engine using live company data.'
  };
}

async function callProvider({ user, message, history, config }) {
  const tools = getAllowedTools(user);
  const messages = [
    { role: 'system', content: `${SYSTEM_PROMPT}\nCompany: ${config.name}. Currency: ${config.currency}. Timezone: ${config.timezone}.` },
    ...history
      .filter((item) => item && ['user', 'assistant'].includes(item.role) && typeof item.content === 'string')
      .slice(-6)
      .map((item) => ({ role: item.role, content: item.content.slice(0, 2000) })),
    { role: 'user', content: String(message).slice(0, 2000) }
  ];

  const toolTrace = [];
  for (let round = 0; round < 3; round += 1) {
    const response = await fetch(`${env.aiBaseUrl.replace(/\/$/, '')}/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${env.aiApiKey}`
      },
      body: JSON.stringify({
        model: env.aiModel,
        messages,
        tools: tools.length ? tools : undefined,
        tool_choice: tools.length ? 'auto' : undefined,
        temperature: 0.2,
        max_tokens: 500
      }),
      signal: AbortSignal.timeout(env.aiTimeoutMs)
    });

    if (!response.ok) {
      const text = await response.text().catch(() => '');
      throw new Error(`provider responded ${response.status} ${text.slice(0, 160)}`);
    }
    const payload = await response.json();
    const choice = payload.choices?.[0]?.message;
    if (!choice) throw new Error('empty provider response');

    if (choice.tool_calls?.length) {
      messages.push({ role: 'assistant', content: choice.content || '', tool_calls: choice.tool_calls });
      for (const call of choice.tool_calls.slice(0, 4)) {
        let args = {};
        try {
          args = JSON.parse(call.function?.arguments || '{}');
        } catch {
          args = {};
        }
        let result;
        try {
          result = await executeTool(call.function?.name, args, user);
        } catch (error) {
          result = { error: error.message };
        }
        toolTrace.push({ tool: call.function?.name, args, ok: !result?.error });
        messages.push({
          role: 'tool',
          tool_call_id: call.id,
          content: JSON.stringify(result).slice(0, 4000)
        });
      }
      continue;
    }

    return { answer: String(choice.content || '').trim() || 'No answer was returned.', toolTrace };
  }

  return { answer: 'I could not complete that request within the allowed tool-call budget.', toolTrace };
}

async function safeTool(name, args, user) {
  try {
    return { ok: true, data: await executeTool(name, args, user) };
  } catch (error) {
    return { ok: false, error: error.message };
  }
}

export async function deterministicAnswer({ user, message, org, config, todayKey }) {
  const text = String(message || '').toLowerCase();
  const toolTrace = [];
  const says = (pattern) => pattern.test(text);

  if (says(/leave\s*policy|policy.*leave|entitle|leave rules|how many (annual|sick|casual)/)) {
    const policy = config.leavePolicy;
    const unpaid = policy.unpaid === null || policy.unpaid === undefined ? 'unlimited' : `${policy.unpaid} days`;
    return {
      answer: `${org.name} leave policy: Annual ${policy.annual} days, Sick ${policy.sick} days, Casual ${policy.casual} days, Unpaid ${unpaid}. Weekends (${config.weekendDays.map((day) => ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][day]).join(', ')}) and public holidays are excluded. Pending requests reserve your balance; approval is required from HR.`,
      toolTrace
    };
  }

  if (says(/leave balance|remaining.*leave|balance.*leave|my leave/)) {
    const result = await safeTool('get_my_leave_balance', {}, user);
    if (!result.ok) {
      return { answer: `Leave balances are only available to employee accounts. ${result.error}`, toolTrace };
    }
    toolTrace.push({ tool: 'get_my_leave_balance', ok: true });
    const lines = result.data.balances.map((balance) =>
      `${balance.label}: ${balance.unlimited ? 'unlimited' : `${balance.available} of ${balance.quota} day(s) available`}${balance.pending ? ` (${balance.pending} pending)` : ''}`
    );
    return { answer: `Your ${result.data.year} leave balances — ${lines.join('; ')}.`, toolTrace };
  }

  if (says(/pending.*leave|leave.*pending|approve.*leave/)) {
    const result = await safeTool('get_leave_summary', {}, user);
    if (!result.ok) return { answer: `You do not have access to company-wide leave data. ${result.error}`, toolTrace };
    toolTrace.push({ tool: 'get_leave_summary', ok: true });
    const byType = result.data.pendingByType.map((row) => `${row.type}: ${row.requests}`).join(', ');
    return {
      answer: `There are ${result.data.pending} pending leave request(s)${byType ? ` (${byType})` : ''}; ${result.data.approvedThisMonth} approved request(s) started this month. Please approve or reject pending requests from the Leave module — I cannot change approvals.`,
      toolTrace
    };
  }

  if (says(/late|late comer|arrived late/)) {
    const dateMatch = text.match(/\d{4}-\d{2}-\d{2}/);
    const date = dateMatch?.[0] || todayKey;
    const result = await safeTool('get_late_comers', { date }, user);
    if (!result.ok) return { answer: `Late-arrival data is available to HR and Admin only. ${result.error}`, toolTrace };
    toolTrace.push({ tool: 'get_late_comers', ok: true });
    if (!result.data.count) {
      return { answer: `No late arrivals were recorded on ${formatDateLabel(date)}. (Note: this reflects check-ins after ${config.workStartTime} + ${config.graceMinutes} min grace.)`, toolTrace };
    }
    const list = result.data.employees
      .slice(0, 8)
      .map((employee) => `${employee.name} (${employee.code}) — ${employee.lateMinutes} min late`).join('; ');
    return { answer: `${result.data.count} employee(s) arrived late on ${formatDateLabel(date)}: ${list}.`, toolTrace };
  }

  if (says(/attendance.*(today|summary)|today.*attendance|present|absent/)) {
    const dateMatch = text.match(/\d{4}-\d{2}-\d{2}/);
    const date = dateMatch?.[0] || todayKey;
    const result = await safeTool('get_attendance_summary', { date }, user);
    if (!result.ok) {
      return { answer: `Company-wide attendance summaries are available to HR and Admin. Employees can view their own history in the Attendance module. ${result.error}`, toolTrace };
    }
    toolTrace.push({ tool: 'get_attendance_summary', ok: true });
    const summary = result.data;
    return {
      answer: `Attendance for ${formatDateLabel(date)}: ${summary.present} present, ${summary.late} late, ${summary.halfDay} half-day, ${summary.missingCheckout} missing checkout, ${summary.absent} absent, ${summary.onLeave} on approved leave. Attendance rate: ${summary.attendanceRate === null ? 'n/a' : `${summary.attendanceRate}%`}.`,
      toolTrace
    };
  }

  if (says(/payroll|salary|payslip|net pay|payroll summary/)) {
    const result = await safeTool('get_payroll_summary', {}, user);
    if (!result.ok) return { answer: `Payroll summaries are restricted to HR and Admin. Your own payslips are available under Payslips. ${result.error}`, toolTrace };
    toolTrace.push({ tool: 'get_payroll_summary', ok: true });
    const latest = result.data.latest;
    if (!latest) return { answer: 'No payroll has been generated yet. HR can create a draft from the Payroll module.', toolTrace };
    return {
      answer: `Latest payroll (${latest.period}) is ${latest.status}: ${latest.employees} employee(s), gross ${money(latest.currency, latest.gross)}, deductions ${money(latest.currency, latest.deductions)}, tax ${money(latest.currency, latest.tax)}, net ${money(latest.currency, latest.net)}.`,
      toolTrace
    };
  }

  if (says(/headcount|how many (employees|people|staff)|total employees|employees.*company/)) {
    const result = await safeTool('get_headcount', {}, user);
    if (!result.ok) return { answer: `Headcount is restricted to HR and Admin. ${result.error}`, toolTrace };
    toolTrace.push({ tool: 'get_headcount', ok: true });
    const departments = Object.entries(result.data.departments).map(([name, count]) => `${name}: ${count}`).join(', ');
    return { answer: `${org.name} currently has ${result.data.headcount} active employee(s). Departments — ${departments || 'none configured'}.`, toolTrace };
  }

  if (says(/find|search|look up|who is|profile/)) {
    const query = String(message).replace(/.*?(?:find|search|look up|who is)\s*/i, '').replace(/[?.!]+$/, '').trim();
    if (!query) return { answer: 'Tell me a name, employee code, or department to search for.', toolTrace };
    const result = await safeTool('search_employees', { query }, user);
    if (!result.ok) return { answer: `Directory search is restricted to HR and Admin. ${result.error}`, toolTrace };
    toolTrace.push({ tool: 'search_employees', ok: true });
    if (!result.data.count) return { answer: `No active employee matched “${query}”.`, toolTrace };
    const list = result.data.employees.map((employee) => `${employee.name} (${employee.code}, ${employee.designation}, ${employee.department})`).join('; ');
    return { answer: `${result.data.count} match(es) for “${query}”: ${list}.`, toolTrace };
  }

  if (says(/department|team/) && says(/attendance|summary|issue/)) {
    const result = await safeTool('get_headcount', {}, user);
    if (!result.ok) return { answer: 'Department summaries require HR or Admin access.', toolTrace };
    toolTrace.push({ tool: 'get_headcount', ok: true });
    const summary = await safeTool('get_attendance_summary', {}, user);
    if (summary.ok) toolTrace.push({ tool: 'get_attendance_summary', ok: true });
    const departments = Object.entries(result.data.departments).map(([name, count]) => `${name}: ${count} employee(s)`).join(', ');
    return {
      answer: `Department overview: ${departments}. Today: ${summary.ok ? `${summary.data.present} present, ${summary.data.late} late, ${summary.data.absent} absent` : 'attendance summary unavailable'}. Ask me about late arrivals for a specific date for more detail.`,
      toolTrace
    };
  }

  return {
    answer: 'I can help with headcount, today’s attendance, late arrivals, pending leave, your leave balance, payroll summaries, leave policy, and directory search. Try: “Show today’s attendance summary”.',
    toolTrace
  };
}

/** Natural-language → structured leave form suggestion. Never submits anything. */
export function parseLeaveSuggestion({ text, org, todayKey }) {
  const config = orgConfig(org);
  const input = String(text || '');
  const lower = input.toLowerCase();
  const type = /sick|medical|fever|flu/.test(lower)
    ? 'sick'
    : /casual|personal|family/.test(lower)
      ? 'casual'
      : /unpaid|without pay|lwop/.test(lower)
        ? 'unpaid'
        : 'annual';

  const dates = extractDates(input);
  let startDate = dates[0] || null;
  let endDate = dates[1] || dates[0] || null;
  const validation = [];

  if (!startDate) {
    validation.push({ level: 'error', message: 'No clear dates found. Add dates such as 2026-11-02 to 2026-11-06.' });
  }
  if (startDate && !dates[1]) {
    validation.push({ level: 'info', message: 'Assumed a single-day request. Adjust the end date if needed.' });
  }
  if (startDate && endDate && startDate > endDate) {
    validation.push({ level: 'error', message: 'End date is before the start date.' });
    [startDate, endDate] = [endDate, startDate];
  }

  let days = 0;
  if (startDate && endDate) {
    try {
      days = computeLeaveDays({ org, startDate, endDate }).days;
      if (days === 0) validation.push({ level: 'warning', message: 'The range contains only weekends/holidays.' });
      else if (days < 3) validation.push({ level: 'info', message: `${days} working day(s) will be requested after excluding weekends and holidays.` });
    } catch (error) {
      validation.push({ level: 'error', message: error.message });
    }
  }

  const quota = config.leavePolicy[type];
  if (quota !== null && quota !== undefined && days > quota) {
    validation.push({ level: 'warning', message: `This exceeds the annual ${LEAVE_TYPE_LABELS[type].toLowerCase()} quota of ${quota} days (pending requests reserve balance).` });
  }

  const reason = input.length > 200 ? `${input.slice(0, 197)}…` : input;

  return {
    leaveType: type,
    leaveTypeLabel: LEAVE_TYPE_LABELS[type],
    startDate,
    endDate,
    days,
    reason,
    validation,
    readyToSubmit: Boolean(startDate && endDate && days > 0 && !validation.some((item) => item.level === 'error')),
    note: 'Suggestion only — review and submit the form yourself. The AI cannot submit or approve leave.'
  };
}

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];

function extractDates(input) {
  const found = [];
  const push = (dateKey) => {
    if (/^\d{4}-\d{2}-\d{2}$/.test(dateKey) && !found.includes(dateKey)) found.push(dateKey);
  };
  const normalized = input
    .replace(/\b(\d{1,2})(?:st|nd|rd|th)\b/gi, '$1')
    .replace(/(\d{1,2})[\/.-](\d{1,2})[\/.-](\d{4})/g, (match, d, m, y) => {
      const day = Number(d);
      const month = Number(m);
      if (day <= 31 && month <= 12) return `${y}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
      return match;
    });

  for (const match of normalized.matchAll(/\b(\d{4}-\d{2}-\d{2})\b/g)) push(match[1]);

  for (const match of normalized.matchAll(/\b(\d{1,2})\s+([A-Za-z]{3,9})\s+(\d{4})\b/g)) {
    const month = MONTHS.indexOf(match[2].slice(0, 3).toLowerCase());
    if (month >= 0) push(`${match[3]}-${String(month + 1).padStart(2, '0')}-${String(Number(match[1])).padStart(2, '0')}`);
  }
  for (const match of normalized.matchAll(/\b([A-Za-z]{3,9})\s+(\d{1,2}),?\s+(\d{4})\b/g)) {
    const month = MONTHS.indexOf(match[1].slice(0, 3).toLowerCase());
    if (month >= 0) push(`${match[3]}-${String(month + 1).padStart(2, '0')}-${String(Number(match[2])).padStart(2, '0')}`);
  }
  if (!found.length && /\btomorrow\b/i.test(input)) {
    const dateKey = addDays(new Date().toISOString().slice(0, 10), 1);
    push(dateKey);
  }
  return found.sort();
}
